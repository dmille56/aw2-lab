def combat_bonuses(co_id: int, power: int, unit_type: int) -> tuple[int, int]:
    """Native 0x080430B0/0x08043120: class plus direct/indirect group."""
    group = UNIT_COMBAT_GROUPS[unit_type]
    stats = CO_COMBAT_GROUPS[f"{co_id}:{power}"]
    attack, defense = stats[group]
    if group:
        minimum = UNIT_DATA[unit_type][5]
        category = 6 if minimum > 1 else 5 if minimum == 1 else 7
        attack += stats[category][0]
        defense += stats[category][1]
    return attack, defense
